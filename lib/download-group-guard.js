const fs = require('fs')
const path = require('path')

const normalize = (jid) => String(jid || '').replace(/:\d+(?=@)/, '')
const isUser = (jid) => /@(s\.whatsapp\.net|lid)$/.test(jid)
const isGroup = (jid) => String(jid || '').endsWith('@g.us')

function isGroupStatus(raw) {
  if (!isGroup(raw.key?.remoteJid)) return false
  let body = raw.message || {}
  for (let depth = 0; depth < 5; depth++) {
    if (body.groupStatusMessage || body.groupStatusMessageV2 || body.groupStatusMentionMessage) return true
    const wrapped = body.ephemeralMessage || body.viewOnceMessage || body.viewOnceMessageV2
    if (!wrapped?.message) return false
    body = wrapped.message
  }
  return false
}

function isStatusAdmin(raw, metadata, socket) {
  const own = [socket.user?.id, socket.user?.jid, socket.user?.lid].map(normalize).filter(Boolean)
  const sender = [raw.key?.participant, raw.key?.participantAlt].map(normalize).filter(Boolean)
  const participants = Array.isArray(metadata) ? metadata : metadata?.participants || []
  return raw.key?.fromMe === true || participants.some(participant => participant.admin &&
    [participant.id, participant.lid, participant.phoneNumber].map(normalize).some(id => sender.includes(id))) ||
    sender.some(id => own.includes(id)) ||
    [metadata?.owner, metadata?.ownerPn].map(normalize).some(id => sender.includes(id))
}

function createGuard(root = path.join(__dirname, '..'), options = {}) {
  const statePath = path.join(root, 'download-group-guard.json')
  const reportPath = path.join(root, 'download-group-guard-status.json')
  let state
  const startupNotified = new Set()
  try { state = JSON.parse(fs.readFileSync(statePath, 'utf8')) } catch (error) {
    if (error.code !== 'ENOENT') throw error
    state = { groups: {} }
    const groups = JSON.parse(fs.readFileSync(path.join(root, 'auto-download-groups.json'), 'utf8'))
    for (const jid of groups) state.groups[jid] = { enabled: true, blocked: [], released: [] }
  }
  function save() {
    fs.writeFileSync(statePath + '.tmp', JSON.stringify(state, null, 2))
    fs.renameSync(statePath + '.tmp', statePath)
  }
  function group(jid) { return state.groups[jid] }
  function owner(raw, socket) {
    if (raw.key?.fromMe) return true
    const own = [socket.user?.id, socket.user?.jid, socket.user?.lid].map(normalize).filter(Boolean)
    return [raw.key?.participant, raw.key?.participantAlt].some(jid => own.includes(normalize(jid)))
  }
  function botSignature(raw) {
    const id = String(raw.key?.id || '')
    // Known Baileys-generated IDs; these are heuristics, not a WhatsApp bot flag.
    if (/^3EB0(?:[A-F0-9]{18}|[A-F0-9]{36})$/i.test(id) || /^BAE5[A-F0-9]{12}$/i.test(id)) return true
    let body = raw.message || {}
    for (let depth = 0; depth < 4; depth++) {
      const wrapped = body.ephemeralMessage || body.viewOnceMessage || body.viewOnceMessageV2 || body.documentWithCaptionMessage
      if (!wrapped?.message) break
      body = wrapped.message
    }
    const text = body.conversation || body.extendedTextMessage?.text || body.videoMessage?.caption || body.imageMessage?.caption || body.documentMessage?.caption || ''
    return /\bvideo generated by\b|\b(?:video|audio) downloaded\b|\b(?:powered|generated) by .{0,50}\bbot\b/i.test(text)
  }
  function shouldBlock(raw, socket = {}, remember = false) {
    const cfg = group(raw.key?.remoteJid)
    if (!cfg?.enabled || owner(raw, socket) || !raw.message || raw.message.protocolMessage || isGroupStatus(raw)) return false
    const senders = [raw.key?.participant, raw.key?.participantAlt].map(normalize).filter(isUser)
    if (!senders.length || senders.some(jid => cfg.released.includes(jid))) return false
    const detected = senders.some(jid => cfg.blocked.includes(jid)) || botSignature(raw)
    if (detected && remember) {
      const added = senders.filter(jid => !cfg.blocked.includes(jid))
      if (added.length) { cfg.blocked.push(...added); save() }
    }
    return detected
  }
  async function shouldDeleteGroupStatus(raw, socket, settings = {}) {
    if (!group(raw.key?.remoteJid)?.enabled || !isGroupStatus(raw) || owner(raw, socket)) return false
    if (settings?.enabled === false) return false
    const ignored = new Set((settings?.jids || []).map(normalize))
    const jid = raw.key.remoteJid
    if (ignored.has(normalize(jid))) return false
    const metadata = await socket.groupMetadata(jid)
    const sender = [raw.key.participant, raw.key.participantAlt].map(normalize).filter(Boolean)
    const participants = Array.isArray(metadata) ? metadata : metadata?.participants || []
    // Missing sender/roster information is not evidence that someone is a non-admin.
    if (!sender.length || !participants.some(p => [p.id, p.lid, p.phoneNumber, p.jid]
      .map(normalize).some(id => sender.includes(id)))) return false
    return !isStatusAdmin(raw, metadata, socket)
  }
  function configure(jid, action, targets = []) {
    if (!jid.endsWith('@g.us')) throw new Error('Use this command inside the download group.')
    if (!group(jid)) {
      if (action !== 'on') throw new Error('This group is not protected. Use .botguard on first.')
      state.groups[jid] = { enabled: true, blocked: [], released: [] }
    }
    const cfg = group(jid)
    if (action === 'on' || action === 'off') cfg.enabled = action === 'on'
    else if (action === 'block' || action === 'release') {
      targets = targets.map(normalize).filter(isUser)
      if (!targets.length) throw new Error('Reply to the sender or mention their account.')
      const add = action === 'block' ? 'blocked' : 'released'
      const remove = action === 'block' ? 'released' : 'blocked'
      cfg[add] = [...new Set([...cfg[add], ...targets])]
      cfg[remove] = cfg[remove].filter(jid => !targets.includes(jid))
    } else throw new Error('Use .botguard on, off, or status.')
    save()
    return cfg
  }
  const reports = {}
  function report(jid, value) {
    reports[jid] = { ...reports[jid], ...value, updatedAt: new Date().toISOString() }
    fs.writeFileSync(reportPath, JSON.stringify(reports, null, 2))
  }
  function attach(socket) {
    const seen = new Set()
    const getAntiGstatus = options.getAntiGstatus || (async () => ({}))
    const deleteMessage = raw => {
      const id = `${raw.key.remoteJid}:${raw.key.participant}:${raw.key.id}`
      if (seen.has(id)) return
      seen.add(id)
      if (seen.size > 2000) seen.delete(seen.values().next().value)
      socket.sendMessage(raw.key.remoteJid, { delete: { ...raw.key, fromMe: false } })
        .then(() => report(raw.key.remoteJid, { lastDeletion: new Date().toISOString(), lastError: null }))
        .catch(error => {
          seen.delete(id)
          report(raw.key.remoteJid, { lastError: String(error.message).slice(0, 200) })
        })
    }
    socket.ev.on('messages.upsert', ({ messages, type }) => {
      if (type !== 'notify') return
      for (const raw of messages || []) {
        try {
          if (shouldBlock(raw, socket, true)) {
            deleteMessage(raw)
            continue
          }
          if (!isGroupStatus(raw)) continue
          getAntiGstatus()
            .then(settings => shouldDeleteGroupStatus(raw, socket, settings))
            .then(deleteStatus => { if (deleteStatus) deleteMessage(raw) })
            .catch(error => report(raw.key.remoteJid, { lastError: String(error.message).slice(0, 200) }))
        } catch (error) {
          process.stderr.write(`[download-group-guard] ${error.message}\n`)
        }
      }
    })
    socket.ev.on('connection.update', async ({ connection }) => {
      if (connection !== 'open') return
      const ownJid = normalize(socket.user?.id || socket.user?.jid || socket.user?.lid)
      if (ownJid && !startupNotified.has(ownJid)) {
        startupNotified.add(ownJid)
        socket.sendMessage(ownJid, {
          text: '✅ KENTECH AI is online\n\nThe WhatsApp bot started successfully. Use .menu to view commands.',
        }).catch(error => {
          startupNotified.delete(ownJid)
          process.stderr.write(`[kentech-startup] ${error.message}\n`)
        })
      }
      for (const [jid, cfg] of Object.entries(state.groups)) {
        if (!cfg.enabled) continue
        try {
          const meta = await socket.groupMetadata(jid)
          const own = [socket.user?.id, socket.user?.jid, socket.user?.lid].map(normalize).filter(Boolean)
          const participant = meta.participants.find(p => [p.id, p.lid, p.phoneNumber].some(v => own.includes(normalize(v))))
          report(jid, { admin: Boolean(participant?.admin), connected: true })
        } catch (error) { report(jid, { admin: false, lastError: String(error.message).slice(0, 200) }) }
      }
    })
    return socket
  }
  return { group, configure, shouldBlock, shouldDeleteGroupStatus, botSignature, owner, attach }
}

let guard
function getGuard() { return guard || (guard = createGuard()) }
function install() {
  const loader = require('./baileys')
  if (loader.loadBaileys.downloadGroupGuard) return
  const original = loader.loadBaileys
  const wrapped = async function (...args) {
    const api = await original.apply(this, args)
    return { ...api, makeWASocket: (...options) => getGuard().attach(api.makeWASocket(...options)) }
  }
  wrapped.downloadGroupGuard = true
  loader.loadBaileys = wrapped
}

module.exports = { createGuard, getGuard, install, normalize }
